func TestLockPartialFailure(t *testing.T) {
	lockPath := filepath.Join(t.TempDir(), "mise.lock")
	var entries []string
	fake := newFake(func(dir string, args []string) (string, error) {
		switch toolArg(args) {
		case "":
			return miseErrors(
				"failed to resolve aqua:anthropics/claude-code@latest for lockfile "+dir+"/mise.lock",
				"unable to fetch versions for aqua:anthropics/claude-code: registry not available",
			), errors.New("exit status 1")
		case "go":
			entries = append(entries, goArm64, goX64)
		case "jq":
			entries = append(entries, jqArm64, jqX64)
		case "aqua:anthropics/claude-code":
			return miseErrors(
				"failed to resolve aqua:anthropics/claude-code@latest for lockfile "+dir+"/mise.lock",
				"unable to fetch versions for aqua:anthropics/claude-code: registry not available",
			), errors.New("exit status 1")
		}
		writeLock(t, filepath.Join(dir, "mise.lock"), entries...)
		return "", nil
	})

	res, err := Lock(context.Background(), fake, []Tool{goTool, jqTool, ccTool}, bothPl, lockPath)
	require.NoError(t, err)
	assert.Equal(t, []string{"go", "jq"}, res.Locked)
	assert.True(t, res.Changed)

	reason := "failed to resolve aqua:anthropics/claude-code@latest for lockfile mise.lock: " +
		"unable to fetch versions for aqua:anthropics/claude-code: registry not available"
	assert.Equal(t, []ToolError{
		{Key: "claude-code", Tool: "aqua:anthropics/claude-code", Platform: "linux-arm64", Reason: reason},
		{Key: "claude-code", Tool: "aqua:anthropics/claude-code", Platform: "linux-x64", Reason: reason},
	}, res.Failed)

	var tools []string
	for _, c := range fake.lockCalls {
		tools = append(tools, toolArg(c.args))
	}
	assert.Equal(t, []string{"", "aqua:anthropics/claude-code", "go", "jq"}, tools)

	written, err := ReadLock(lockPath)
	require.NoError(t, err)
	assert.Empty(t, written.Check([]Tool{goTool, jqTool}, "linux-x64"))
	assert.Equal(t, "", written.Version("aqua:anthropics/claude-code"))
}

