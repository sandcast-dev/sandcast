func TestLockRevertsFailedTools(t *testing.T) {
	lockPath := filepath.Join(t.TempDir(), "mise.lock")
	writeLock(t, lockPath, goArm64, jqArm64)

	// mise lock --bump: go moves on, jq and uv end up with selectors locked
	// verbatim and no platform tables (what mise writes when it cannot list
	// versions).
	goBumped := strings.ReplaceAll(goArm64, "1.25.14", "1.25.15")
	jqVerbatim := "\n[[tools.jq]]\nversion = \"latest\"\nbackend = \"aqua:jqlang/jq\"\nspecifiers = [\"latest\"]\n"
	uvVerbatim := "\n[[tools.uv]]\nversion = \"0.8\"\nbackend = \"aqua:astral-sh/uv\"\nspecifiers = [\"0.8\"]\n"
	fake := newFake(func(dir string, _ []string) (string, error) {
		writeLock(t, filepath.Join(dir, "mise.lock"), goBumped, jqVerbatim, uvVerbatim)
		return "", nil
	})

	uvTool := Tool{Key: "uv", Tool: "uv", Version: "0.8"}
	res, err := Lock(context.Background(), fake, []Tool{goTool, jqTool, uvTool}, []string{"linux-arm64"}, lockPath, WithBump())
	require.NoError(t, err)
	assert.Equal(t, []string{"go"}, res.Locked)
	require.Len(t, res.Failed, 2)
	assert.Equal(t, "jq", res.Failed[0].Key)
	assert.Equal(t, "uv", res.Failed[1].Key)
	assert.True(t, res.Changed)

	after, err := os.ReadFile(lockPath)
	require.NoError(t, err)
	assert.Equal(t, lockHeader+goBumped+jqArm64, string(after))
}

