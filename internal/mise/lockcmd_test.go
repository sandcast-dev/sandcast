func TestMergeLock(t *testing.T) {
	previous := []byte(lockHeader + goArm64 + jqArm64)
	tests := []struct {
		name     string
		produced []byte
		revert   map[string]bool
		want     string
	}{
		{
			name:     "nothing produced keeps previous",
			produced: nil,
			revert:   map[string]bool{"go": true},
			want:     lockHeader + goArm64 + jqArm64,
		},
		{
			name:     "revert to previous tables",
			produced: []byte(lockHeader + goArm64 + goX64NoChecksum + jqArm64 + jqX64),
			revert:   map[string]bool{"go": true},
			want:     lockHeader + goArm64 + jqArm64 + jqX64,
		},
		{
			name:     "drop a tool without previous tables",
			produced: []byte(lockHeader + goArm64 + "\n[[tools.uv]]\nversion = \"0.8\"\n" + jqArm64),
			revert:   map[string]bool{"uv": true},
			want:     lockHeader + goArm64 + jqArm64,
		},
		{
			name:     "reinsert a tool mise left out, in name order",
			produced: []byte(lockHeader + goArm64),
			revert:   map[string]bool{"jq": true, "aqua:x/y": true},
			want:     lockHeader + goArm64 + jqArm64,
		},
		{
			name:     "reinsert before a later tool",
			produced: []byte(lockHeader + jqArm64),
			revert:   map[string]bool{"go": true},
			want:     lockHeader + goArm64 + jqArm64,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := mergeLock(tt.produced, previous, tt.revert)
			assert.Equal(t, tt.want, string(got))
			_, err := ParseLock(got)
			assert.NoError(t, err)
		})
	}
}

