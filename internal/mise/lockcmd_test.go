// miseErrors formats stderr of a failed mise run the way mise prints it.
func miseErrors(msgs ...string) string {
	var b strings.Builder
	for _, m := range msgs {
		b.WriteString("mise ERROR " + m + "\n")
	}
	b.WriteString("mise ERROR Version: 2026.10.3 macos-arm64 (2026-10-05)\n")
	b.WriteString("mise ERROR Run with --verbose or MISE_VERBOSE=1 for more information\n")
	return b.String()
}

// lockCall is one recorded mise lock invocation.
type lockCall struct {
	dir    string
	args   []string
	env    []string
	config string // mise.toml in dir at call time
	seeded string // mise.lock in dir at call time, "" when absent
}

// fakeMise implements Runner. lock decides the outcome of each mise lock
// call; it may write dir/mise.lock and returns stderr and an error.
type fakeMise struct {
	version     string // stdout of mise --version
	versionErr  error
	lock        func(dir string, args []string) (string, error)
	lockCalls   []lockCall
	versionRuns int
}

func (f *fakeMise) Run(_ context.Context, dir string, env []string, name string, args ...string) ([]byte, []byte, error) {
	if name != "mise" {
		return nil, nil, fmt.Errorf("unexpected command %s", name)
	}
	if len(args) == 1 && args[0] == "--version" {
		f.versionRuns++
		return []byte(f.version), nil, f.versionErr
	}
	if len(args) == 0 || args[0] != "lock" {
		return nil, nil, fmt.Errorf("unexpected mise args %v", args)
	}
	config, _ := os.ReadFile(filepath.Join(dir, "mise.toml"))
	seeded, _ := os.ReadFile(filepath.Join(dir, "mise.lock"))
	f.lockCalls = append(f.lockCalls, lockCall{
		dir: dir, args: append([]string(nil), args...), env: env,
		config: string(config), seeded: string(seeded),
	})
	if f.lock == nil {
		return nil, nil, nil
	}
	stderr, err := f.lock(dir, args)
	return nil, []byte(stderr), err
}

func newFake(lock func(dir string, args []string) (string, error)) *fakeMise {
	return &fakeMise{version: "2026.10.3 macos-arm64 (2026-10-05)\n", lock: lock}
}

func writeLock(t *testing.T, path string, entries ...string) {
	t.Helper()
	require.NoError(t, os.WriteFile(path, []byte(lockHeader+strings.Join(entries, "")), 0o600))
}

// toolArg returns the tool argument of a mise lock call, "" for a full run.
func toolArg(args []string) string {
	for i := 1; i < len(args); i++ {
		switch args[i] {
		case "--platform":
			i++
		case "--bump":
		default:
			return args[i]
		}
	}
	return ""
}

var (
	goTool = Tool{Key: "go", Tool: "go", Version: "1.25"}
	jqTool = Tool{Key: "jq", Tool: "jq"}
	ccTool = Tool{Key: "claude-code", Tool: "aqua:anthropics/claude-code"}
	bothPl = []string{"linux-x64", "linux-arm64"}
)

func envValue(env []string, key string) (string, bool) {
	val, found := "", false
	for _, kv := range env {
		if k, v, _ := strings.Cut(kv, "="); k == key {
			val, found = v, true
		}
	}
	return val, found
}

func TestLockSuccess(t *testing.T) {
	t.Setenv("MISE_GLOBAL_CONFIG_FILE", "/host/config.toml")
	t.Setenv("MISE_ENV", "dev")
	t.Setenv("MISE_GITHUB_TOKEN", "placeholder")

	lockPath := filepath.Join(t.TempDir(), ".sandcast", "mise.lock")
	fake := newFake(func(dir string, _ []string) (string, error) {
		writeLock(t, filepath.Join(dir, "mise.lock"), goArm64, goX64, jqArm64, jqX64)
		return "", nil
	})

	res, err := Lock(context.Background(), fake, []Tool{jqTool, goTool}, bothPl, lockPath)
	require.NoError(t, err)
	assert.Equal(t, []string{"go", "jq"}, res.Locked)
	assert.Empty(t, res.Failed)
	assert.True(t, res.Changed)

	require.Len(t, fake.lockCalls, 1)
	call := fake.lockCalls[0]
	assert.Equal(t, []string{"lock", "--platform", "linux-arm64,linux-x64"}, call.args)
	assert.Equal(t, "", call.seeded)
	assert.Contains(t, call.config, "go = \"1.25\"\njq = \"latest\"\n")
	assert.NotContains(t, call.config, "locked")
	assert.NotContains(t, call.config, "use_versions_host")

	// Environment isolation.
	_, found := envValue(call.env, "MISE_GLOBAL_CONFIG_FILE")
	assert.False(t, found, "host MISE_GLOBAL_CONFIG_FILE must not leak")
	_, found = envValue(call.env, "MISE_ENV")
	assert.False(t, found, "host MISE_ENV must not leak")
	token, _ := envValue(call.env, "MISE_GITHUB_TOKEN")
	assert.Equal(t, "placeholder", token)
	trusted, _ := envValue(call.env, "MISE_TRUSTED_CONFIG_PATHS")
	assert.Equal(t, call.dir, trusted)
	root := filepath.Dir(call.dir)
	ceiling, _ := envValue(call.env, "MISE_CEILING_PATHS")
	assert.Equal(t, root, ceiling)
	for _, key := range []string{"MISE_CONFIG_DIR", "MISE_SYSTEM_CONFIG_DIR", "MISE_DATA_DIR", "MISE_STATE_DIR"} {
		v, ok := envValue(call.env, key)
		require.True(t, ok, key)
		assert.Equal(t, root, filepath.Dir(v), key)
	}

	written, err := ReadLock(lockPath)
	require.NoError(t, err)
	assert.Equal(t, "1.25.14", written.Version("go"))
	_, err = os.Stat(call.dir)
	assert.True(t, errors.Is(err, os.ErrNotExist), "workspace must be removed")
}

