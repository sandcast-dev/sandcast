func TestIsolatedEnv(t *testing.T) {
	ws := workspace{root: "/w", project: "/w/project", config: "/w/config", system: "/w/system", data: "/w/data", state: "/w/state"}
	base := []string{
		"HOME=/home/u",
		"PATH=/usr/bin",
		"MISE_GLOBAL_CONFIG_FILE=/home/u/.config/mise/config.toml",
		"MISE_DATA_DIR=/home/u/.local/share/mise",
		"MISE_USE_VERSIONS_HOST=false",
		"MISE_LOCKED=1",
		"MISE_CACHE_DIR=/home/u/.cache/mise",
		"MISE_GITHUB_TOKEN=placeholder",
		"GITHUB_TOKEN=placeholder",
	}
	env := isolatedEnv(base, ws)

	got := map[string]string{}
	var keys []string
	for _, kv := range env {
		k, v, _ := strings.Cut(kv, "=")
		if _, dup := got[k]; !dup {
			keys = append(keys, k)
		}
		got[k] = v
	}
	sort.Strings(keys)
	assert.Equal(t, []string{
		"GITHUB_TOKEN", "HOME", "MISE_CACHE_DIR", "MISE_CEILING_PATHS", "MISE_COLOR", "MISE_CONFIG_DIR",
		"MISE_DATA_DIR", "MISE_GITHUB_TOKEN", "MISE_STATE_DIR", "MISE_SYSTEM_CONFIG_DIR",
		"MISE_TRUSTED_CONFIG_PATHS", "NO_COLOR", "PATH",
	}, keys)
	assert.Equal(t, "/w/config", got["MISE_CONFIG_DIR"])
	assert.Equal(t, "/w/system", got["MISE_SYSTEM_CONFIG_DIR"])
	assert.Equal(t, "/w/data", got["MISE_DATA_DIR"])
	assert.Equal(t, "/w/state", got["MISE_STATE_DIR"])
	assert.Equal(t, "/w", got["MISE_CEILING_PATHS"])
	assert.Equal(t, "/w/project", got["MISE_TRUSTED_CONFIG_PATHS"])
	assert.Equal(t, "/home/u/.cache/mise", got["MISE_CACHE_DIR"])
}

