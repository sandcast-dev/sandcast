package mise

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// DefaultVersion is the version selector used when a component names none.
const DefaultVersion = "latest"

// ImageConfigDir is the directory mise.toml and mise.lock are copied to in
// the image. It is the only path mise trusts there.
const ImageConfigDir = "/etc/mise"

// configHeader starts every rendered mise.toml.
const configHeader = "# Generated by sandcast. Do not edit: change the manifest and run sandcast plan.\n"

// Tool is one mise-installed component.
type Tool struct {
	// Key is the component key, used in error messages.
	Key string
	// Tool is the mise tool name as written in [tools], for example "go" or
	// "aqua:anthropics/claude-code".
	Tool string
	// Version is the version selector, for example "1.25" or "latest".
	// Empty means DefaultVersion.
	Version string
}

// selector returns the version selector with the default applied.
func (t Tool) selector() string {
	if t.Version == "" {
		return DefaultVersion
	}
	return t.Version
}

// RenderConfig renders the mise.toml installed into the image: lockfile
// mode, locked installs, the lockfile platforms, no contact with the mise
// versions host, ImageConfigDir as the trusted path, and one [tools] entry
// per tool sorted by tool name. platforms are mise platform names.
func RenderConfig(tools []Tool, platforms []string) ([]byte, error) {
	return render(tools, platforms, false)
}

// renderLockConfig renders the mise.toml that sandcast lock resolves on the
// host. It drops locked (resolution needs the network), use_versions_host
// (without the versions host mise sees only the first page of GitHub
// releases and locks unmatched prefixes such as "0.8" verbatim) and
// trusted_config_paths (ignored with a warning outside the global config;
// the environment trusts the temp directory instead).
func renderLockConfig(tools []Tool, platforms []string) ([]byte, error) {
	return render(tools, platforms, true)
}

func render(tools []Tool, platforms []string, forLock bool) ([]byte, error) {
	plats, err := normalizePlatforms(platforms)
	if err != nil {
		return nil, err
	}
	sorted, err := sortTools(tools)
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString(configHeader)
	b.WriteString("\n[settings]\n")
	b.WriteString("lockfile = true\n")
	if !forLock {
		b.WriteString("locked = true\n")
	}
	b.WriteString("lockfile_platforms = " + tomlArray(plats) + "\n")
	if !forLock {
		b.WriteString("use_versions_host = false\n")
		b.WriteString("trusted_config_paths = " + tomlArray([]string{ImageConfigDir}) + "\n")
	}
	b.WriteString("\n[tools]\n")
	for _, t := range sorted {
		b.WriteString(tomlKey(t.Tool) + " = " + tomlString(t.selector()) + "\n")
	}
	return b.Bytes(), nil
}

// normalizePlatforms validates, de-duplicates and sorts mise platform names.
func normalizePlatforms(platforms []string) ([]string, error) {
	if len(platforms) == 0 {
		return nil, fmt.Errorf("no lockfile platform given")
	}
	seen := map[string]bool{}
	var out []string
	for _, p := range platforms {
		if _, err := Target(p); err != nil {
			return nil, err
		}
		if !seen[p] {
			seen[p] = true
			out = append(out, p)
		}
	}
	sort.Strings(out)
	return out, nil
}

// sortTools validates tools and returns a copy sorted by tool name. Two
// components naming the same mise tool are an error.
func sortTools(tools []Tool) ([]Tool, error) {
	byTool := map[string]string{}
	out := make([]Tool, 0, len(tools))
	for _, t := range tools {
		if t.Tool == "" {
			return nil, fmt.Errorf("component %q: empty mise tool name", t.Key)
		}
		if prev, ok := byTool[t.Tool]; ok {
			a, b := prev, t.Key
			if b < a {
				a, b = b, a
			}
			return nil, fmt.Errorf("components %q and %q both install mise tool %q", a, b, t.Tool)
		}
		byTool[t.Tool] = t.Key
		out = append(out, t)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Tool < out[j].Tool })
	return out, nil
}

// tomlKey returns k as a bare TOML key when possible, quoted otherwise.
func tomlKey(k string) string {
	if k == "" {
		return `""`
	}
	for _, r := range k {
		bare := r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_' || r == '-'
		if !bare {
			return tomlString(k)
		}
	}
	return k
}

// tomlString returns s as a TOML basic string.
func tomlString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteString(`\t`)
		case r == '\r':
			b.WriteString(`\r`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// tomlArray returns items as a single-line TOML array of strings.
func tomlArray(items []string) string {
	quoted := make([]string, len(items))
	for i, s := range items {
		quoted[i] = tomlString(s)
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}
