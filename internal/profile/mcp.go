// MCPProfilePrefix starts the id of every generated MCP server profile.
const MCPProfilePrefix = "mcp-"

// MCPCredentialName is the credential name of a generated MCP profile.
const MCPCredentialName = "api_token"

var mcpIDCleanRe = regexp.MustCompile(`[^a-z0-9]+`)

// MCPCredentialVar returns the environment variable that carries the
// credential of one MCP server env entry at runtime (FR-039): the key itself
// when the value is a ${SANDCAST_SECRET_N} placeholder, the referenced
// variable when the value is only a reference such as ${GITHUB_TOKEN}, and
// false for a literal value. The harness scaffolding renders the same
// variable into the agent configuration, so the profile credential and the
// configuration agree.
func MCPCredentialVar(key, value string) (string, bool) {
	if redact.IsPlaceholder(value) {
		return key, true
	}
	return redact.EnvRef(value)
}

// MCPProfiles generates a project-local profile for every MCP server with a
// url whose host and port no endpoint of the referenced profiles covers
// (FR-039, US4 scenario 3). A covering endpoint has the same host, or a
// wildcard host that matches it, and the same port or no port restriction.
// The profile is in the upstream schema: id mcp-<name>, category other, one
// endpoint, the agent binaries, and, when the server's env carries
// credentials (see MCPCredentialVar), a bearer credential declaration that
// names the env vars and never a value, with protocol rest so the gateway
// injects it. Servers without a url, served on loopback, or already covered
// produce a notice instead. A generated profile that fails Lint is an error.
// Profiles are sorted by id.
func MCPProfiles(servers []manifest.MCPServer, referenced Set, agentBinaries []string) ([]*Profile, []string, error) {
	sorted := slices.Clone(servers)
	slices.SortStableFunc(sorted, func(a, b manifest.MCPServer) int { return strings.Compare(a.Name, b.Name) })

	var profiles []*Profile
	var notices []string
	byID := map[string]string{}
	for _, s := range sorted {
		if s.URL == "" {
			notices = append(notices, fmt.Sprintf(
				"MCP server %s runs as a local command; no profile generated, it reaches the network through the profiles of the command it runs", s.Name))
			continue
		}
		host, port, err := mcpEndpoint(s.URL)
		if err != nil {
			return nil, nil, fmt.Errorf("MCP server %s: %w", s.Name, err)
		}
		if isLoopbackHost(host) {
			notices = append(notices, fmt.Sprintf(
				"MCP server %s is served on loopback inside the sandbox; no profile needed", s.Name))
			continue
		}
		if id := coveringProfile(referenced, host, port); id != "" {
			notices = append(notices, fmt.Sprintf(
				"MCP server %s: %s:%d is covered by profile %s; no profile generated", s.Name, host, port, id))
			continue
		}

		id := MCPProfileID(s.Name)
		if id == MCPProfilePrefix {
			return nil, nil, fmt.Errorf("MCP server %q: name gives no valid profile id", s.Name)
		}
		if other, dup := byID[id]; dup {
			return nil, nil, fmt.Errorf("MCP servers %s and %s both map to profile id %s; rename one", other, s.Name, id)
		}
		if _, exists := referenced[id]; exists {
			return nil, nil, fmt.Errorf("MCP server %s: profile %s is already referenced but does not cover %s:%d", s.Name, id, host, port)
		}
		byID[id] = s.Name

		p := mcpProfile(s, id, host, port, agentBinaries)
		if diags := Lint(p, "generated for MCP server "+s.Name); len(diags) > 0 {
			return nil, nil, &LintError{Diagnostics: diags}
		}
		profiles = append(profiles, p)
	}
	slices.SortFunc(profiles, func(a, b *Profile) int { return strings.Compare(a.ID, b.ID) })
	return profiles, notices, nil
}

// MCPProfileID returns mcp-<name> with the name lowercased and every run of
// characters outside a-z and 0-9 replaced by one dash.
func MCPProfileID(name string) string {
	return MCPProfilePrefix + strings.Trim(mcpIDCleanRe.ReplaceAllString(strings.ToLower(name), "-"), "-")
}

// mcpProfile builds the profile for one server.
func mcpProfile(s manifest.MCPServer, id, host string, port uint32, agentBinaries []string) *Profile {
	p := &Profile{
		ID:          id,
		DisplayName: "MCP server " + s.Name,
		Description: fmt.Sprintf("MCP server %s at %s:%d, generated by sandcast from the manifest", s.Name, host, port),
		Category:    "other",
		Endpoints:   []Endpoint{{Host: host, Port: port}},
		Binaries:    slices.Clone(agentBinaries),
	}
	var envVars []string
	for _, k := range manifest.SortedKeys(s.Env) {
		if v, ok := MCPCredentialVar(k, s.Env[k]); ok && !slices.Contains(envVars, v) {
			envVars = append(envVars, v)
		}
	}
	if len(envVars) == 0 {
		return p
	}
	slices.Sort(envVars)
	p.Credentials = []Credential{{
		Name:        MCPCredentialName,
		Description: "Credential of MCP server " + s.Name,
		EnvVars:     envVars,
		Required:    true,
		AuthStyle:   "bearer",
		HeaderName:  "authorization",
	}}
	p.Discovery = Discovery{Credentials: []string{MCPCredentialName}}
	// The gateway injects a credential only into inspected traffic. MCP over
	// HTTP uses POST and GET, and DELETE to end a session, so access is full.
	p.Endpoints[0].Protocol = "rest"
	p.Endpoints[0].Access = "full"
	p.Endpoints[0].Enforcement = "enforce"
	return p
}

// mcpEndpoint returns the lowercased host and the port of an MCP server url:
// the explicit port, else 443 for https and 80 for http. User information
// is skipped without parsing, since it may hold a placeholder.
func mcpEndpoint(raw string) (string, uint32, error) {
	scheme, rest, ok := strings.Cut(raw, "://")
	if !ok {
		return "", 0, fmt.Errorf("url has no scheme")
	}
	scheme = strings.ToLower(scheme)
	var defaultPort uint32
	switch scheme {
	case "https":
		defaultPort = 443
	case "http":
		defaultPort = 80
	default:
		return "", 0, fmt.Errorf("url scheme %q is not http or https", scheme)
	}
	authority := rest
	if i := strings.IndexAny(rest, "/?#"); i >= 0 {
		authority = rest[:i]
	}
	if at := strings.LastIndex(authority, "@"); at >= 0 {
		authority = authority[at+1:]
	}
	u, err := url.Parse(scheme + "://" + authority)
	if err != nil {
		return "", 0, fmt.Errorf("parse url host: %w", err)
	}
	host := strings.TrimSuffix(strings.ToLower(u.Hostname()), ".")
	if host == "" {
		return "", 0, fmt.Errorf("url has no host")
	}
	if u.Port() == "" {
		return host, defaultPort, nil
	}
	port, err := strconv.ParseUint(u.Port(), 10, 32)
	if err != nil || port < 1 || port > 65535 {
		return "", 0, fmt.Errorf("url port %q is not between 1 and 65535", u.Port())
	}
	return host, uint32(port), nil
}

// isLoopbackHost reports localhost and loopback or unspecified addresses,
// which the sandbox reaches without the proxy.
func isLoopbackHost(host string) bool {
	if host == "localhost" || strings.HasSuffix(host, ".localhost") {
		return true
	}
	addr, err := netip.ParseAddr(host)
	return err == nil && (addr.IsLoopback() || addr.IsUnspecified())
}

// coveringProfile returns the id of the first referenced profile, in id
// order, with an endpoint that covers host and port, or "".
func coveringProfile(referenced Set, host string, port uint32) string {
	for _, e := range referenced.Entries() {
		if e.Profile == nil {
			continue
		}
		for i := range e.Profile.Endpoints {
			ep := &e.Profile.Endpoints[i]
			if hostCovers(ep.Host, host) && portCovers(ep, port) {
				return e.Profile.ID
			}
		}
	}
	return ""
}

// hostCovers reports whether an endpoint host, exact or with OpenShell
// wildcards, matches host. "*" matches one label, a glob in the first label
// matches within that label, and "**" as the first label matches one or
// more labels.
func hostCovers(pattern, host string) bool {
	pattern = strings.TrimSuffix(strings.ToLower(strings.TrimSpace(pattern)), ".")
	if !strings.Contains(pattern, "*") {
		return pattern == host
	}
	pl := strings.Split(pattern, ".")
	hl := strings.Split(host, ".")
	if pl[0] == "**" {
		suffix := pl[1:]
		return len(hl) > len(suffix) && labelsMatch(suffix, hl[len(hl)-len(suffix):])
	}
	return len(pl) == len(hl) && labelsMatch(pl, hl)
}

func labelsMatch(patterns, labels []string) bool {
	for i, p := range patterns {
		if ok, err := path.Match(p, labels[i]); err != nil || !ok {
			return false
		}
	}
	return true
}

// portCovers reports whether an endpoint allows port: listed in ports, equal
// to port, or no port restriction at all.
func portCovers(ep *Endpoint, port uint32) bool {
	if len(ep.Ports) > 0 {
		return slices.Contains(ep.Ports, port)
	}
	return ep.Port == 0 || ep.Port == port
}
