// Pin is the OpenShell release whose default policy and validation limits this
// package reproduces (tag v0.1.3, commit e1f3c82c).
const Pin = "v0.1.3"

// DefaultsFile is the pinned upstream default policy at the root of the
// policy directory.
const DefaultsFile = "default-" + Pin + ".yaml"

// Upstream limits from crates/openshell-policy/src/lib.rs and
// crates/openshell-policy-schema/src/lib.rs at the pin.
const (
	// MaxFilesystemPaths bounds read_only plus read_write (MAX_FILESYSTEM_PATHS).
	MaxFilesystemPaths = 256
	// MaxPathLength bounds a single filesystem path in bytes (MAX_PATH_LENGTH).
	MaxPathLength = 4096
	// MaxDocumentBytes bounds a policy document (ParseLimits.max_bytes).
	MaxDocumentBytes = 4 * 1024 * 1024
	// SandboxIdentity is the only named process identity upstream accepts.
	SandboxIdentity = "sandbox"
)

const (
	policyVersion           = 1
	minSandboxID            = 1
	maxSandboxID            = math.MaxUint32 - 1
	landlockBestEffort      = "best_effort"
	landlockHardRequirement = "hard_requirement"
	displayPathBytes        = 64
)

const header = "# OpenShell sandbox policy generated by sandcast. Do not edit.\n" +
	"# Base: OpenShell " + Pin + " restrictive_default_policy() plus component image needs.\n" +
	"# Network rules come from provider profiles at runtime, never from this file.\n"

// document is the on-disk shape of an OpenShell policy file, restricted to
// the sections sandcast writes. Field names follow the upstream serde names.
type document struct {
	Version          int               `yaml:"version"`
	FilesystemPolicy *filesystemPolicy `yaml:"filesystem_policy,omitempty"`
	Landlock         *landlockPolicy   `yaml:"landlock,omitempty"`
	Process          *processPolicy    `yaml:"process,omitempty"`
	NetworkPolicies  map[string]any    `yaml:"network_policies"`
}

type filesystemPolicy struct {
	IncludeWorkdir bool     `yaml:"include_workdir"`
	ReadOnly       []string `yaml:"read_only,omitempty"`
	ReadWrite      []string `yaml:"read_write,omitempty"`
}

type landlockPolicy struct {
	Compatibility string `yaml:"compatibility,omitempty"`
}

type processPolicy struct {
	RunAsUser  string `yaml:"run_as_user,omitempty"`
	RunAsGroup string `yaml:"run_as_group,omitempty"`
}

// Defaults is the parsed pinned upstream default policy. The pinned default
// has no process section and no network rules; Render takes the process
// identity from Input and always writes an empty network section.
type Defaults struct {
	// IncludeWorkdir is filesystem_policy.include_workdir.
	IncludeWorkdir bool
	// ReadOnly is filesystem_policy.read_only in file order.
	ReadOnly []string
	// ReadWrite is filesystem_policy.read_write in file order.
	ReadWrite []string
	// LandlockCompatibility is landlock.compatibility.
	LandlockCompatibility string
}

// Input is the image-specific part of the policy.
type Input struct {
	// ReadOnly lists the read-only paths from the components' image needs.
	ReadOnly []string
	// ReadWrite lists the read-write paths from the components' image needs.
	ReadWrite []string
	// RunAsUser is the final image user: "sandbox" or a numeric UID.
	RunAsUser string
	// RunAsGroup is the final image group: "sandbox" or a numeric GID.
	RunAsGroup string
}

// LoadDefaults reads and checks DefaultsFile at the root of fsys.
func LoadDefaults(fsys fs.FS) (*Defaults, error) {
	data, err := fs.ReadFile(fsys, DefaultsFile)
	if err != nil {
		return nil, fmt.Errorf("read default policy: %w", err)
	}
	doc, err := decode(data)
	if err != nil {
		return nil, fmt.Errorf("default policy %s: %w", DefaultsFile, err)
	}
	switch {
	case doc.FilesystemPolicy == nil:
		return nil, fmt.Errorf("default policy %s: filesystem_policy is missing", DefaultsFile)
	case doc.Landlock == nil:
		return nil, fmt.Errorf("default policy %s: landlock is missing", DefaultsFile)
	case doc.Process != nil:
		return nil, fmt.Errorf("default policy %s: process must be absent, the upstream default leaves it to the runtime", DefaultsFile)
	}
	return &Defaults{
		IncludeWorkdir:        doc.FilesystemPolicy.IncludeWorkdir,
		ReadOnly:              slices.Clone(doc.FilesystemPolicy.ReadOnly),
		ReadWrite:             slices.Clone(doc.FilesystemPolicy.ReadWrite),
		LandlockCompatibility: doc.Landlock.Compatibility,
	}, nil
}

// Render produces the image-embedded policy: the upstream default paths
// merged with the input paths (normalized, sorted, deduplicated, and dropped
// from read_only when also read-write), process from the input identity, and
// an empty network section. The output is deterministic and passes Validate.
func Render(d *Defaults, in Input) ([]byte, error) {
	if d == nil {
		return nil, errors.New("render policy: defaults are nil")
	}
	var violations []error
	readOnly := mergePaths(&violations, d.ReadOnly, in.ReadOnly)
	readWrite := mergePaths(&violations, d.ReadWrite, in.ReadWrite)
	readOnly = slices.DeleteFunc(readOnly, func(p string) bool {
		_, found := slices.BinarySearch(readWrite, p)
		return found
	})
	if in.RunAsUser == "" {
		violations = append(violations, errors.New("run_as_user is required"))
	}
	if in.RunAsGroup == "" {
		violations = append(violations, errors.New("run_as_group is required"))
	}
	doc := document{
		Version: policyVersion,
		FilesystemPolicy: &filesystemPolicy{
			IncludeWorkdir: d.IncludeWorkdir,
			ReadOnly:       readOnly,
			ReadWrite:      readWrite,
		},
		Landlock:        &landlockPolicy{Compatibility: d.LandlockCompatibility},
		Process:         &processPolicy{RunAsUser: in.RunAsUser, RunAsGroup: in.RunAsGroup},
		NetworkPolicies: map[string]any{},
	}
	violations = append(violations, doc.violations()...)
	if len(violations) > 0 {
		return nil, fmt.Errorf("render policy: %w", errors.Join(violations...))
	}
	body, err := yaml.MarshalWithOptions(doc, yaml.Indent(2), yaml.IndentSequence(true))
	if err != nil {
		return nil, fmt.Errorf("render policy: encode: %w", err)
	}
	out := make([]byte, 0, len(header)+len(body))
	out = append(out, header...)
	out = append(out, body...)
	if err := Validate(out); err != nil {
		return nil, fmt.Errorf("render policy: %w", err)
	}
	return out, nil
}

// Validate applies the upstream parse rules and safety limits to a policy
// document: version 1, no unknown fields, absolute paths without ".."
// components, "/" never read-write, at most MaxFilesystemPaths paths of at
// most MaxPathLength bytes, a known landlock compatibility, and process
// identities that are "sandbox" or a non-root numeric ID. It also rejects any
// network rule, since the pinned default has none (FR-033).
func Validate(doc []byte) error {
	_, err := decode(doc)
	return err
}

// decode parses data strictly and returns all violations as one error.
func decode(data []byte) (*document, error) {
	if len(data) > MaxDocumentBytes {
		return nil, fmt.Errorf("policy exceeds the %d-byte input limit", MaxDocumentBytes)
	}
	var doc document
	if err := yaml.UnmarshalWithOptions(data, &doc, yaml.Strict()); err != nil {
		return nil, fmt.Errorf("parse policy: %w", err)
	}
	if violations := doc.violations(); len(violations) > 0 {
		return nil, fmt.Errorf("invalid policy: %w", errors.Join(violations...))
	}
	return &doc, nil
}

// violations mirrors validate_sandbox_policy() for the sections sandcast
// writes, in the upstream order, with the upstream messages.
func (doc *document) violations() []error {
	var out []error
	if doc.Version != policyVersion {
		out = append(out, fmt.Errorf("unsupported policy version %d; expected version %d", doc.Version, policyVersion))
	}
	if p := doc.Process; p != nil {
		out = appendIdentity(out, "run_as_user", p.RunAsUser)
		out = appendIdentity(out, "run_as_group", p.RunAsGroup)
	}
	if l := doc.Landlock; l != nil {
		switch l.Compatibility {
		case "", landlockBestEffort, landlockHardRequirement:
		default:
			out = append(out, fmt.Errorf("invalid landlock.compatibility '%s'; accepted: %s, %s",
				l.Compatibility, landlockBestEffort, landlockHardRequirement))
		}
	}
	if fsp := doc.FilesystemPolicy; fsp != nil {
		if total := len(fsp.ReadOnly) + len(fsp.ReadWrite); total > MaxFilesystemPaths {
			out = append(out, fmt.Errorf("too many filesystem paths (%d > %d)", total, MaxFilesystemPaths))
		}
		for _, p := range fsp.ReadOnly {
			out = append(out, pathViolations(p)...)
		}
		for _, p := range fsp.ReadWrite {
			out = append(out, pathViolations(p)...)
		}
		for _, p := range fsp.ReadWrite {
			if strings.TrimRight(p, "/") == "" {
				out = append(out, fmt.Errorf("read-write path is overly broad: %s", p))
			}
		}
	}
	if len(doc.NetworkPolicies) > 0 {
		out = append(out, fmt.Errorf("network_policies must be empty: the OpenShell %s default policy has no network rules and endpoints come from provider profiles", Pin))
	}
	return out
}

// pathViolations checks one filesystem path like upstream: length first,
// then absolute, then ".." components.
func pathViolations(p string) []error {
	if len(p) > MaxPathLength {
		return []error{fmt.Errorf("path exceeds maximum length (%d > %d): %s", len(p), MaxPathLength, displayPath(p))}
	}
	var out []error
	if !strings.HasPrefix(p, "/") {
		out = append(out, fmt.Errorf("path must be absolute (start with '/'): %s", p))
	}
	if slices.Contains(strings.Split(p, "/"), "..") {
		out = append(out, fmt.Errorf("path contains '..' traversal component: %s", p))
	}
	return out
}

// mergePaths validates every path, normalizes the valid ones lexically like
// upstream normalize_path(), and returns them sorted and deduplicated.
// Invalid paths are reported to violations and left out.
func mergePaths(violations *[]error, lists ...[]string) []string {
	var out []string
	for _, list := range lists {
		for _, p := range list {
			if v := pathViolations(p); len(v) > 0 {
				*violations = append(*violations, v...)
				continue
			}
			out = append(out, path.Clean(p))
		}
	}
	slices.Sort(out)
	return slices.Compact(out)
}

// appendIdentity reports an explicit process identity that is neither
// "sandbox" nor a numeric ID in the upstream range. Empty means omitted.
func appendIdentity(out []error, field, value string) []error {
	if value == "" || value == SandboxIdentity {
		return out
	}
	if id, err := strconv.ParseUint(value, 10, 32); err == nil && id >= minSandboxID && id <= maxSandboxID {
		return out
	}
	return append(out, fmt.Errorf("%s must be '%s' or a numeric UID/GID in range [%d, %d], got '%s'",
		field, SandboxIdentity, minSandboxID, maxSandboxID, value))
}

// displayPath shortens an overlong path for error messages.
func displayPath(p string) string {
	if len(p) <= displayPathBytes {
		return p
	}
	return strings.ToValidUTF8(p[:displayPathBytes], "") + "..."
}
