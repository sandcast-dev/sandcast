// Shell session environment (issue #11). OpenShell starts interactive
// sessions with a cleared environment (HOME, USER, TERM, SHELL and a default
// PATH only) and always with bash, so neither the image ENV nor the zsh
// configuration reaches them unless shell startup files restore it.
const (
	// SessionEnvPath is the generated environment script. Login shells read
	// it through /etc/profile.d, every zsh through the system zshenv.
	SessionEnvPath    = "/etc/profile.d/sandcast-session.sh"
	SessionContextDir = "session"
	// SessionContextFile is the build-context path of the script.
	SessionContextFile = SessionContextDir + "/sandcast-session.sh"
)

// zshSwitchHook is appended to the system bashrc for the OpenShell target
// when shell.program is zsh. It switches interactive terminal sessions to a
// zsh login shell and leaves "bash -lc" commands alone. SANDCAST_IN_ZSH keeps
// a bash started from that zsh in bash; SANDCAST_NO_ZSH=1 opts out. It is
// written with printf '%s', so it must not contain a single quote.
const zshSwitchHook = `case $- in *i*) if [ -t 0 ] && [ -z "${SANDCAST_NO_ZSH-}" ] && [ -z "${SANDCAST_IN_ZSH-}" ] && [ -x /bin/zsh ]; then SANDCAST_IN_ZSH=1 SHELL=/bin/zsh; export SANDCAST_IN_ZSH SHELL; exec /bin/zsh -l; fi ;; esac`

var sessionTemplate = template.Must(template.New("65-session").Parse(`# 65-session: environment for shell sessions, which OpenShell starts with a cleared environment
USER root
COPY {{.ContextFile}} {{.Path}}
RUN chmod 0644 {{.Path}} \
 && if command -v zsh >/dev/null 2>&1; then \
      rc=/etc/zsh/zshenv && if [ -f /etc/zshenv ]; then rc=/etc/zshenv; fi \
      && install -d "${rc%/*}" \
      && (grep -qs '{{.Path}}' "$rc" || printf '%s\n' '' \
        '# sandcast-session: the image environment for every zsh' \
        '[ -r {{.Path}} ] && . {{.Path}}' \
        '# The home directory is the workspace and has no .zshrc: no new-user wizard.' \
        'zsh-newuser-install() { :; }' >> "$rc"); \
    fi
{{- if .SwitchToZsh}} \
 && for rc in /etc/bash.bashrc /etc/bashrc; do \
      if [ -f "$rc" ] && ! grep -qs 'SANDCAST_NO_ZSH' "$rc"; then \
        printf '%s\n' '' \
          '# sandcast-session: OpenShell starts bash; interactive terminal sessions switch to zsh.' \
          '# Set SANDCAST_NO_ZSH=1 to stay in bash.' \
          '{{.Hook}}' >> "$rc"; \
      fi; \
    done
{{- end}}
`))

// SessionScript renders the environment script for shell sessions: the
// variables the image sets with ENV (components, harnesses and, when mise
// installs tools, the MISE_* settings) and the mise shims first on PATH.
// Sourcing it twice keeps one shims entry. The output depends only on the
// plan.
func SessionScript(p *plan.Plan) string {
	var b strings.Builder
	b.WriteString("# Generated by sandcast: the image environment for shell sessions.\n")
	b.WriteString("# OpenShell starts sessions with a cleared environment, so the variables the\n")
	b.WriteString("# image sets with ENV are exported again for login shells and every zsh.\n")
	for _, e := range sessionEnv(p) {
		b.WriteString("export " + e.Name + "=" + singleQuote(e.Value) + "\n")
	}
	if usesMise(p) {
		b.WriteString(`case ":${PATH}:" in` + "\n")
		b.WriteString(`  *":` + plan.MiseShims + `:"*) ;;` + "\n")
		b.WriteString(`  *) PATH="` + plan.MiseShims + `:${PATH}" ;;` + "\n")
		b.WriteString("esac\nexport PATH\n")
	}
	return b.String()
}

// sessionEnv is the image environment in ENV order: the 20-user variables,
// then the mise settings of the 30-mise layer, which win on a name clash.
// Names and values that envInstruction refuses are left out; Assemble
// fails on them before the script is written.
func sessionEnv(p *plan.Plan) []plan.EnvVar {
	var mise []plan.EnvVar
	if usesMise(p) {
		mise = plan.MiseEnv()
	}
	shadowed := map[string]bool{}
	for _, e := range mise {
		shadowed[e.Name] = true
	}
	var out []plan.EnvVar
	for _, e := range p.Image.Env {
		if !shadowed[e.Name] && component.ValidEnvName(e.Name) && !component.HasControl(e.Value) {
			out = append(out, e)
		}
	}
	return append(out, mise...)
}

// usesMise reports whether the image has the 30-mise layer.
func usesMise(p *plan.Plan) bool {
	for _, c := range p.Components {
		if c.InstallerKind == component.KindMise && c.Action != plan.ActionSkip {
			return true
		}
	}
	return false
}

// switchToZsh reports whether interactive OpenShell sessions switch from
// bash to zsh.
func switchToZsh(p *plan.Plan) bool {
	return p.Target == manifest.TargetOpenShell && p.Shell.Program == "zsh"
}

// needsSession reports whether the image gets the 65-session section.
func needsSession(p *plan.Plan) bool {
	return len(sessionEnv(p)) > 0 || usesMise(p) || switchToZsh(p)
}

func sessionSection(p *plan.Plan) (string, error) {
	if !needsSession(p) {
		return "", nil
	}
	return execTemplate(sessionTemplate, map[string]any{
		"ContextFile": SessionContextFile,
		"Path":        SessionEnvPath,
		"SwitchToZsh": switchToZsh(p),
		"Hook":        zshSwitchHook,
	})
}

// singleQuote quotes s for sh, bash and zsh.
func singleQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
