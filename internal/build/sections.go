// dotfileNameEncoder percent-encodes '%' and '/' (in one pass, so an encoded
// '%' is never re-read). Percent-encoding is injective, and the result is one
// flat file name.
var dotfileNameEncoder = strings.NewReplacer("%", "%25", "/", "%2F")

// DotfileContextFile is the build-context path a baked dotfile is staged at.
// It is derived deterministically from the (unique) relocation target so two
// builds of the same plan stage the same files, and it is injective: two
// distinct targets never share a context file, which would silently bake one
// dotfile's content into another's destination. The previous encoding
// (underscore doubled, slash to underscore) collided for /x/a/_b and /x/a_/b.
func DotfileContextFile(target string) string {
	return DotfileContextDir + "/" + dotfileNameEncoder.Replace(strings.TrimPrefix(target, "/"))
}

// dotfilesSection renders the 62-dotfiles section, empty when the plan bakes
// no dotfiles.
func dotfilesSection(p *plan.Plan) (string, error) {
	if len(p.Dotfiles) == 0 {
		return "", nil
	}
	type row struct{ Context, Target string }
	rows := make([]row, 0, len(p.Dotfiles))
	for _, d := range p.Dotfiles {
		rows = append(rows, row{Context: DotfileContextFile(d.RelocatedTo), Target: d.RelocatedTo})
	}
	return execTemplate(dotfilesTemplate, map[string]any{"Dotfiles": rows})
}

func execTemplate(t *template.Template, data any) (string, error) {
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("render section %s: %w", t.Name(), err)
	}
	return buf.String(), nil
}

// loginShellSpec is the final user's login shell and the image CMD.
type loginShellSpec struct {
	// Path is the passwd login shell of the final user.
	Path string
	// CmdArgs follow Path in the image CMD.
	CmdArgs []string
}

// cmd renders the image CMD argv.
func (s loginShellSpec) cmd() string {
	argv := make([]string, 0, 1+len(s.CmdArgs))
	for _, a := range append([]string{s.Path}, s.CmdArgs...) {
		argv = append(argv, fmt.Sprintf("%q", a))
	}
	return strings.Join(argv, ", ")
}

// loginShell picks the shell for the final user and the CMD in one switch
// on the shell kind. The bash and sh cases use a baked launcher (not
// /bin/bash or a login /bin/sh) so no $HOME startup file in the mounted
// workspace is ever sourced (spec 003 US2, FR-002, research R1/R2); a
// launcher sets up the environment itself and must not get -l, so it is the
// sole CMD argument. zsh starts as a login shell with -l, which is safe
// because ZDOTDIR (set in the global zshenv) relocates its startup files out
// of $HOME.
func loginShell(p *plan.Plan) loginShellSpec {
	switch plan.ShellKind(p) {
	case "zsh":
		return loginShellSpec{Path: shell.ZshProgram, CmdArgs: []string{"-l"}}
	case "bash":
		return loginShellSpec{Path: plan.ShellLoginPath}
	default:
		return loginShellSpec{Path: plan.ShLoginPath}
	}
}

// shellSection renders the 60-shell section for the plan's shell kind. For
// the OpenShell target it also makes that shell the final user's passwd
// login shell (loginShellTemplate) and bakes the hooks for shells the
// runtime starts directly; the container target keeps the base image user
// untouched.
func shellSection(p *plan.Plan) (string, error) {
	body, err := shellKindSection(p)
	if err != nil {
		return "", err
	}
	if plan.ShellKind(p) != "zsh" && plan.HasZsh(p) {
		zshenv, err := execTemplate(zshEnvTemplate, zshEnvData(p))
		if err != nil {
			return "", err
		}
		body += zshenv
	}
	if p.Target != manifest.TargetOpenShell {
		return body, nil
	}
	login, err := execTemplate(loginShellTemplate, map[string]any{
		"Shell":  loginShell(p).Path,
		"User":   p.FinalUser.Name,
		"UserRe": strings.ReplaceAll(p.FinalUser.Name, ".", `\.`),
	})
	if err != nil {
		return "", err
	}
	exports := hookExports(p)
	for _, e := range exports {
		// The 20-user section renders the image env through envInstruction
		// first; this guards a hand-built plan with the same rule.
		if err := checkEnvVar(e.Name, e.Value); err != nil {
			return "", fmt.Errorf("shell hook export: %w", err)
		}
	}
	targets := hookTargets(p)
	env := sessionEnvPath(p)
	hooks, err := execTemplate(hookTemplate, map[string]any{
		"LoginHookPath":     plan.LoginHookPath,
		"LoginHook":         strings.TrimRight(shell.LoginHook(exports, targets, plan.RedirectHome, env), "\n"),
		"RedirectHome":      plan.RedirectHome,
		"RedirectProfile":   strings.TrimRight(shell.RedirectHomeProfile(), "\n"),
		"BashrcHook":        strings.TrimRight(shell.BashrcHook(exports, targets, env), "\n"),
		"SystemBashrcPaths": plan.SystemBashrcPaths,
		"HookBegin":         shell.HookBegin,
		"HookEnd":           shell.HookEnd,
		"HookInstall":       hookInstallScript,
	})
	if err != nil {
		return "", err
	}
	return body + login + hooks, nil
}

// zshEnvData is the template data of the global zshenv block.
func zshEnvData(p *plan.Plan) map[string]any {
	return map[string]any{
		"ZDotDir":       plan.ZDotDir,
		"ZshEnvPaths":   plan.ZshEnvPaths,
		"ZshEnvBlock":   strings.TrimRight(shell.ZshEnvBlock(plan.ZDotDir, sessionEnvPath(p)), "\n"),
		"ZshEnvBegin":   shell.ZshEnvBegin,
		"ZshEnvEnd":     shell.ZshEnvEnd,
		"ZshEnvInstall": zshEnvInstallScript,
	}
}

// shellKindSection renders the shell-specific part of the 60-shell section.
func shellKindSection(p *plan.Plan) (string, error) {
	env := sessionEnvPath(p)
	data := map[string]any{
		"SessionEnv":     env != "",
		"EnvContextFile": SessionEnvContextFile,
		"EnvPath":        plan.SessionEnvPath,
		"Prefix":         plan.RelocationPrefix,
	}
	switch plan.ShellKind(p) {
	case "zsh":
		data["RCPath"] = p.Shell.RCPath
		data["ContextFile"] = ShellContextFile(p.Shell.Program)
		for k, v := range zshEnvData(p) {
			data[k] = v
		}
		return execTemplate(shellZshTemplate, data)
	case "bash":
		// The launcher always reads plan.BashRCPath: the curated
		// configuration when the manifest has one, an empty file otherwise
		// (bash chosen from the image facts).
		data["RCPath"] = plan.BashRCPath
		data["HasRC"] = p.Shell.RCPath != ""
		data["ContextFile"] = ShellContextFile(p.Shell.Program)
		data["ShellLoginPath"] = plan.ShellLoginPath
		data["Launcher"] = strings.TrimRight(shell.LoginLauncher(plan.BashRCPath, env), "\n")
		return execTemplate(shellBashTemplate, data)
	default:
		data["ProfileScriptPath"] = plan.ProfileScriptPath
		data["ShLoginPath"] = plan.ShLoginPath
		data["Launcher"] = strings.TrimRight(shell.ShLoginLauncher(plan.ProfileScriptPath, env), "\n")
		return execTemplate(shellShTemplate, data)
	}
}

// envInstruction renders the NAME=value part of an ENV instruction, refusing
// what checkEnvVar refuses.
func envInstruction(e plan.EnvVar) (string, error) {
	if err := checkEnvVar(e.Name, e.Value); err != nil {
		return "", err
	}
	return e.Name + "=" + envValue(e.Value), nil
}

// checkEnvVar refuses an environment variable that cannot be written into a
// generated file as one line: a name that is not a portable variable name,
// or a value with a control character such as a line break, would add
// Containerfile or hook lines, whatever produced the plan.
func checkEnvVar(name, value string) error {
	if !component.ValidEnvName(name) {
		return fmt.Errorf("env name %q must match [A-Za-z_][A-Za-z0-9_]*", name)
	}
	if component.HasControl(value) {
		return fmt.Errorf("env %q: value contains a control character", name)
	}
	return nil
}

// dirArg renders an image directory as one shell word. Quoting cannot keep a
// line break inside the RUN instruction, so control characters are refused,
// as are relative paths.
func dirArg(p string) (string, error) {
	if !strings.HasPrefix(p, "/") || component.HasControl(p) {
		return "", fmt.Errorf("image directory %q must be an absolute path without control characters", p)
	}
	return shell.QuoteIfNeeded(p), nil
}

// envValue quotes an ENV value unless it consists of safe characters only.
// Callers refuse control characters first (envInstruction).
func envValue(v string) string {
	safe := v != ""
	for _, r := range v {
		isSafe := r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("_./:-@+=,", r)
		if !isSafe {
			safe = false
			break
		}
	}
	if safe {
		return v
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`).Replace(v) + `"`
}
