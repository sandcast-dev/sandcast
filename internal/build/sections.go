// sessionEnvInstall is the start of every 60-shell section: the session
// environment script (spec 002 R-04, /etc/profile.d/sandcast-env.sh), when
// the plan needs one. Login shells read it through /etc/profile; the
// launchers, the hooks and the global zshenv source it (see shell), so a
// session that a runtime starts with a cleared environment gets the MISE_*
// settings, the component and relocation environment and the shims first on
// PATH whatever its entry point.
const sessionEnvInstall = `{{- if .SessionEnv}}
COPY {{.EnvContextFile}} {{.EnvPath}}
RUN chmod 0644 {{.EnvPath}}
{{- end}}`

// The shell section relocates the interactive environment out of the
// overmounted home (spec 003, research R1/R2). zsh sets ZDOTDIR in its global
// zshenv (both /etc/zsh/zshenv and /etc/zshenv, see plan.ZshEnvPaths) so it
// never reads $HOME; bash gets a baked rcfile launched with
// --noprofile --rcfile so it never reads any workspace startup file; any other
// login shell gets /bin/sh with a minimal baked default.
var shellZshTemplate = template.Must(template.New("60-shell").Parse(`# 60-shell: curated zsh configuration relocated out of the overmounted home (ZDOTDIR)
USER root` + sessionEnvInstall + `
{{- if .RCPath}}
COPY {{.ContextFile}} {{.RCPath}}
RUN chmod 0644 {{.RCPath}}
{{- end}}
RUN <<'SANDCAST_EOF'
set -eu
install -d {{.ZDotDir}} /etc/zsh
zshenv_block=/tmp/sandcast-zshenv zshenv_begin='{{.ZshEnvBegin}}' zshenv_end='{{.ZshEnvEnd}}'
cat > "$zshenv_block" <<'SANDCAST_ZSHENV'
{{.ZshEnvBlock}}
SANDCAST_ZSHENV
for f in{{range .ZshEnvPaths}} {{.}}{{end}}; do
{{.ZshEnvInstall}}done
rm -f "$zshenv_block"
SANDCAST_EOF
`))

// zshEnvTemplate installs the global zshenv block in an image whose curated
// shell is not zsh but which has zsh (in the base image or as a component):
// a zsh the user starts then reads its startup files from the ZDOTDIR tree,
// which holds no .zshrc, and never a workspace ~/.zshrc or ~/.zshenv, and it
// gets the session environment and no new-user wizard (plan.HasZsh).
var zshEnvTemplate = template.Must(template.New("60-shell-zshenv").Parse(`RUN <<'SANDCAST_EOF'
set -eu
install -d {{.ZDotDir}} /etc/zsh
zshenv_block=/tmp/sandcast-zshenv zshenv_begin='{{.ZshEnvBegin}}' zshenv_end='{{.ZshEnvEnd}}'
cat > "$zshenv_block" <<'SANDCAST_ZSHENV'
{{.ZshEnvBlock}}
SANDCAST_ZSHENV
for f in{{range .ZshEnvPaths}} {{.}}{{end}}; do
{{.ZshEnvInstall}}done
rm -f "$zshenv_block"
SANDCAST_EOF
`))

// zshEnvInstallScript appends the block in the file $zshenv_block to the
// global zshenv $f. The block of a previous sandcast build between
// $zshenv_begin and $zshenv_end (a base image that sandcast built, or a
// rebuild after an upgrade), or the bare export line of a build before the
// block existed, is removed first rather than kept, so the file always
// carries the current block once; the build log says when that happened.
const zshEnvInstallScript = `  if grep -qsF "$zshenv_begin" "$f" || grep -qs '^export ZDOTDIR=.* SANDCAST_SESSION=1' "$f"; then
    echo "sandcast: replacing the zshenv block of a previous sandcast build in $f" >&2
    awk -v b="$zshenv_begin" -v e="$zshenv_end" '$0 == b { skip = 1 } !skip && !(index($0, "export ZDOTDIR=") == 1 && index($0, " SANDCAST_SESSION=1") > 0) { print } $0 == e { skip = 0 }' "$f" > "$f.sandcast"
  else
    cat "$f" > "$f.sandcast" 2>/dev/null || :
  fi
  cat "$zshenv_block" >> "$f.sandcast"
  mv "$f.sandcast" "$f"
  chmod 0644 "$f"
`

// The bash launcher is written with "exec bash" and the build substitutes
// the absolute path of the image's bash, found with a PATH of the system
// directories only. The hooks replace an interactive bash with the launcher,
// and a curated rc commonly prepends $HOME/bin to the PATH, so a PATH lookup
// at run time could pick a bash wrapper committed into the workspace.
var shellBashTemplate = template.Must(template.New("60-shell").Parse(`# 60-shell: curated bash configuration with a baked login launcher (no $HOME startup files)
USER root` + sessionEnvInstall + `
RUN install -d {{.Prefix}}
{{- if .HasRC}}
COPY {{.ContextFile}} {{.RCPath}}
RUN chmod 0644 {{.RCPath}}
{{- else}}
RUN : > {{.RCPath}} && chmod 0644 {{.RCPath}}
{{- end}}
RUN <<'SANDCAST_EOF'
set -eu
cat > {{.ShellLoginPath}} <<'SANDCAST_LAUNCH'
{{.Launcher}}
SANDCAST_LAUNCH
bash_bin=$(PATH=/usr/local/bin:/usr/bin:/bin command -v bash)
sed -i "s|^exec bash |exec $bash_bin |" {{.ShellLoginPath}}
grep -q "^exec $bash_bin " {{.ShellLoginPath}}
chmod 0755 {{.ShellLoginPath}}
SANDCAST_EOF
`))

