func execTemplate(t *template.Template, data any) (string, error) {
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("render section %s: %w", t.Name(), err)
	}
	return buf.String(), nil
}

// loginShell picks the shell for the created user and CMD. The bash case uses
// the baked launcher (not /bin/bash) so no $HOME startup file is ever sourced
// (spec 003 US2, research R1).
func loginShell(p *plan.Plan) string {
	switch plan.ShellKind(p) {
	case "zsh":
		return "/bin/zsh"
	case "bash":
		return plan.ShellLoginPath
	default:
		return "/bin/sh"
	}
}

// shellSection renders the 60-shell section for the plan's shell kind.
func shellSection(p *plan.Plan) (string, error) {
	switch plan.ShellKind(p) {
	case "zsh":
		return execTemplate(shellZshTemplate, map[string]any{
			"RCPath":      p.Shell.RCPath,
			"ContextFile": ShellContextFile(p.Shell.Program),
			"ZDotDir":     plan.ZDotDir,
			"ZshEnvPath":  plan.ZshEnvPath,
			"ZshEnvLine":  shell.Quote(shell.ZshEnvExport(plan.ZDotDir)),
		})
	case "bash":
		return execTemplate(shellBashTemplate, map[string]any{
			"RCPath":         p.Shell.RCPath,
			"RCPath0":        plan.BashRCPath,
			"ContextFile":    ShellContextFile(p.Shell.Program),
			"ShellLoginPath": plan.ShellLoginPath,
			"Launcher":       strings.TrimRight(shell.LoginLauncher(plan.BashRCPath), "\n"),
		})
	default:
		return execTemplate(shellShTemplate, map[string]any{
			"ProfileScriptPath": plan.ProfileScriptPath,
		})
	}
}

// envInstruction renders the NAME=value part of an ENV instruction. A name
// that is not a portable variable name, or a value with a control character
// such as a line break, would add Containerfile lines, so both are refused
// whatever produced the plan.
func envInstruction(e plan.EnvVar) (string, error) {
	if !component.ValidEnvName(e.Name) {
		return "", fmt.Errorf("env name %q must match [A-Za-z_][A-Za-z0-9_]*", e.Name)
	}
	if component.HasControl(e.Value) {
		return "", fmt.Errorf("env %q: value contains a control character", e.Name)
	}
	return e.Name + "=" + envValue(e.Value), nil
}

// dirArg renders an image directory as one shell word. Quoting cannot keep a
// line break inside the RUN instruction, so control characters are refused,
// as are relative paths.
func dirArg(p string) (string, error) {
	if !strings.HasPrefix(p, "/") || component.HasControl(p) {
		return "", fmt.Errorf("image directory %q must be an absolute path without control characters", p)
	}
	return shell.QuoteIfNeeded(p), nil
}

// envValue quotes an ENV value unless it consists of safe characters only.
// Callers refuse control characters first (envInstruction).
func envValue(v string) string {
	safe := v != ""
	for _, r := range v {
		isSafe := r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("_./:-@+=,", r)
		if !isSafe {
			safe = false
			break
		}
	}
	if safe {
		return v
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`).Replace(v) + `"`
}

// cmdFor renders the image CMD argv. The bash launcher makes bash interactive
// itself and must not be passed -l (a login bash would read profile files,
// not the baked --rcfile), so it is the sole argument; zsh and sh start as
// login shells with -l.
func cmdFor(sh string) string {
	if sh == plan.ShellLoginPath {
		return fmt.Sprintf("%q", sh)
	}
	return fmt.Sprintf("%q, %q", sh, "-l")
}
