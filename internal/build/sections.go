// The shell section relocates the interactive environment out of the
// overmounted home (spec 003, research R1/R2). zsh sets ZDOTDIR in
// /etc/zshenv so it never reads $HOME; bash gets a baked rcfile launched with
// --noprofile --norc so it never reads any workspace startup file; any other
// login shell gets /bin/sh with a minimal baked default.
var shellZshTemplate = template.Must(template.New("60-shell").Parse(`# 60-shell: curated zsh configuration relocated out of the overmounted home (ZDOTDIR)
USER root
{{- if .RCPath}}
COPY {{.ContextFile}} {{.RCPath}}
RUN chmod 0644 {{.RCPath}}
{{- end}}
RUN install -d {{.ZDotDir}} \
 && (grep -qs 'ZDOTDIR={{.ZDotDir}}' {{.ZshEnvPath}} 2>/dev/null \
     || printf '%s\n' {{.ZshEnvLine}} >> {{.ZshEnvPath}}) \
 && chmod 0644 {{.ZshEnvPath}}
`))

var shellBashTemplate = template.Must(template.New("60-shell").Parse(`# 60-shell: curated bash configuration with a baked login launcher (no $HOME startup files)
USER root
{{- if .RCPath}}
COPY {{.ContextFile}} {{.RCPath}}
RUN chmod 0644 {{.RCPath}}
{{- else}}
RUN : > {{.RCPath0}} && chmod 0644 {{.RCPath0}}
{{- end}}
RUN <<'SANDCAST_EOF'
set -eu
cat > {{.ShellLoginPath}} <<'SANDCAST_LAUNCH'
{{.Launcher}}
SANDCAST_LAUNCH
chmod 0755 {{.ShellLoginPath}}
SANDCAST_EOF
`))

var shellShTemplate = template.Must(template.New("60-shell").Parse(`# 60-shell: minimal default environment (the login shell is neither zsh nor bash)
USER root
RUN <<'SANDCAST_EOF'
set -eu
cat > {{.ProfileScriptPath}} <<'SANDCAST_PROFILE'
# Written by sandcast: minimal environment for sh under the home overmount.
# The relocation variables are also set as image ENV; this is the sh fallback.
SANDCAST_PROFILE
chmod 0644 {{.ProfileScriptPath}}
cat > {{.ShLoginPath}} <<'SANDCAST_LAUNCH'
{{.Launcher}}
SANDCAST_LAUNCH
chmod 0755 {{.ShLoginPath}}
SANDCAST_EOF
`))

// The dotfiles section bakes each redacted non-shell dotfile to its
// relocation target outside the home (spec 003 US3). The relocation env
// variables are set image-wide in the 20-user section via the plan's
// RelocationEnv, so this section only copies files.
// The dotfile target is quoted with the same dirArg helper the 20-user
// directories use: the plan already restricts a relocation target to a safe
// absolute path (plan.resolveDotfiles), and this is defense in depth so a
// target can never inject into the RUN instruction (spec 003 US3, constitution
// IV). The COPY source lives under the fixed, sanitized DotfileContextDir.
var dotfilesTemplate = template.Must(template.New("62-dotfiles").Funcs(template.FuncMap{"dir": dirArg}).Parse(`# 62-dotfiles: baked configuration relocated out of the overmounted home
USER root
{{- range .Dotfiles}}
COPY {{.Context}} {{dir .Target}}
RUN chmod 0644 {{dir .Target}}
{{- end}}
`))

var policyTemplate = template.Must(template.New("80-policy").Parse(`# 80-policy: OpenShell sandbox policy (filesystem, landlock, process; no network entries)
USER root
COPY policy.yaml {{.Path}}
RUN chmod 0644 {{.Path}}
`))

// The footer clears the base image's entrypoint (the community base sets
// /bin/bash), so CMD starts the login shell on manual runs; OpenShell
// replaces both anyway.
var footerTemplate = template.Must(template.New("90-footer").Parse(`# 90-footer
WORKDIR {{.WorkDir}}
USER {{.User}}
ENTRYPOINT []
CMD [{{.Cmd}}]
`))

// DotfileContextFile is the build-context path a baked dotfile is staged at.
// It is derived deterministically from the (unique) relocation target so two
// builds of the same plan stage the same files. The encoding is injective:
// an original underscore is doubled before a path separator becomes a single
// underscore, so two targets that differ only by '/' vs '_' never collapse to
// the same context file (which would silently bake one dotfile's content into
// another's destination).
func DotfileContextFile(target string) string {
	s := strings.TrimPrefix(target, "/")
	s = strings.ReplaceAll(s, "_", "__")
	s = strings.ReplaceAll(s, "/", "_")
	return DotfileContextDir + "/" + s
}

// dotfilesSection renders the 62-dotfiles section, empty when the plan bakes
// no dotfiles.
func dotfilesSection(p *plan.Plan) (string, error) {
	if len(p.Dotfiles) == 0 {
		return "", nil
	}
	type row struct{ Context, Target string }
	rows := make([]row, 0, len(p.Dotfiles))
	for _, d := range p.Dotfiles {
		rows = append(rows, row{Context: DotfileContextFile(d.RelocatedTo), Target: d.RelocatedTo})
	}
	return execTemplate(dotfilesTemplate, map[string]any{"Dotfiles": rows})
}

func execTemplate(t *template.Template, data any) (string, error) {
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("render section %s: %w", t.Name(), err)
	}
	return buf.String(), nil
}

// loginShell picks the shell for the created user and CMD. The bash and sh
// cases use a baked launcher (not /bin/bash or a login /bin/sh) so no $HOME
// startup file in the mounted workspace is ever sourced (spec 003 US2,
// FR-002, research R1/R2). zsh is safe as a real login shell because ZDOTDIR
// (set in /etc/zshenv) relocates its startup files out of $HOME.
func loginShell(p *plan.Plan) string {
	switch plan.ShellKind(p) {
	case "zsh":
		return "/bin/zsh"
	case "bash":
		return plan.ShellLoginPath
	default:
		return plan.ShLoginPath
	}
}

// shellSection renders the 60-shell section for the plan's shell kind.
func shellSection(p *plan.Plan) (string, error) {
	switch plan.ShellKind(p) {
	case "zsh":
		return execTemplate(shellZshTemplate, map[string]any{
			"RCPath":      p.Shell.RCPath,
			"ContextFile": ShellContextFile(p.Shell.Program),
			"ZDotDir":     plan.ZDotDir,
			"ZshEnvPath":  plan.ZshEnvPath,
			"ZshEnvLine":  shell.Quote(shell.ZshEnvExport(plan.ZDotDir)),
		})
	case "bash":
		return execTemplate(shellBashTemplate, map[string]any{
			"RCPath":         p.Shell.RCPath,
			"RCPath0":        plan.BashRCPath,
			"ContextFile":    ShellContextFile(p.Shell.Program),
			"ShellLoginPath": plan.ShellLoginPath,
			"Launcher":       strings.TrimRight(shell.LoginLauncher(plan.BashRCPath), "\n"),
		})
	default:
		return execTemplate(shellShTemplate, map[string]any{
			"ProfileScriptPath": plan.ProfileScriptPath,
			"ShLoginPath":       plan.ShLoginPath,
			"Launcher":          strings.TrimRight(shell.ShLoginLauncher(plan.ProfileScriptPath), "\n"),
		})
	}
}

// envInstruction renders the NAME=value part of an ENV instruction. A name
// that is not a portable variable name, or a value with a control character
// such as a line break, would add Containerfile lines, so both are refused
// whatever produced the plan.
func envInstruction(e plan.EnvVar) (string, error) {
	if !component.ValidEnvName(e.Name) {
		return "", fmt.Errorf("env name %q must match [A-Za-z_][A-Za-z0-9_]*", e.Name)
	}
	if component.HasControl(e.Value) {
		return "", fmt.Errorf("env %q: value contains a control character", e.Name)
	}
	return e.Name + "=" + envValue(e.Value), nil
}

// dirArg renders an image directory as one shell word. Quoting cannot keep a
// line break inside the RUN instruction, so control characters are refused,
// as are relative paths.
func dirArg(p string) (string, error) {
	if !strings.HasPrefix(p, "/") || component.HasControl(p) {
		return "", fmt.Errorf("image directory %q must be an absolute path without control characters", p)
	}
	return shell.QuoteIfNeeded(p), nil
}

// envValue quotes an ENV value unless it consists of safe characters only.
// Callers refuse control characters first (envInstruction).
func envValue(v string) string {
	safe := v != ""
	for _, r := range v {
		isSafe := r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("_./:-@+=,", r)
		if !isSafe {
			safe = false
			break
		}
	}
	if safe {
		return v
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`).Replace(v) + `"`
}

// cmdFor renders the image CMD argv. The bash and sh launchers set up the
// environment themselves and must not be passed -l (a login shell would read
// $HOME startup files from the mounted workspace), so each is the sole
// argument; zsh starts as a login shell with -l (ZDOTDIR keeps it out of
// $HOME).
func cmdFor(sh string) string {
	if sh == plan.ShellLoginPath || sh == plan.ShLoginPath {
		return fmt.Sprintf("%q", sh)
	}
	return fmt.Sprintf("%q, %q", sh, "-l")
}
