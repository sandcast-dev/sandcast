// loginShellTemplate makes the shell from loginShell the final user's passwd
// login shell in OpenShell images, whether sandcast created the user or kept
// it from the base image. A kept user (the community base keeps sandbox with
// /bin/bash) would otherwise start /bin/bash -l on su -, sshd or any other
// login through passwd, and that reads the workspace ~/.bash_profile or
// ~/.profile (spec 003 FR-002). usermod lives in sbin, which the community
// base PATH lacks, so sbin is appended; images without usermod (busybox) get
// the passwd entry rewritten. A final user without a passwd entry (a bare
// numeric uid) is left alone. The shell is added to /etc/shells so tools
// that check it (chsh, pam_shells) accept the launcher.
var loginShellTemplate = template.Must(template.New("60-shell-login").Parse(`RUN <<'SANDCAST_EOF'
set -eu
PATH="$PATH:/usr/sbin:/sbin"
grep -qxF {{.Shell}} /etc/shells 2>/dev/null || printf '%s\n' {{.Shell}} >> /etc/shells
if grep -q '^{{.UserRe}}:' /etc/passwd; then
  if command -v usermod >/dev/null 2>&1; then
    usermod -s {{.Shell}} {{.User}}
  else
    sed -i 's|^\({{.UserRe}}:[^:]*:[^:]*:[^:]*:[^:]*:[^:]*:\).*$|\1{{.Shell}}|' /etc/passwd
  fi
fi
SANDCAST_EOF
`))

// hookTemplate bakes the shell hooks for shells that OpenShell starts
// directly, instead of the CMD or the passwd shell (see shell.BashrcHook and
// shell.LoginHook). The login hook goes to /etc/profile.d, the redirect home
// holds the .profile that restores HOME for other POSIX login shells, and
// the bashrc hook is prepended to the system bashrc the image's bash was
// compiled with, found by its path string in the bash binary
// (hookInstallScript). A bash without a system bashrc (Fedora, RHEL) cannot
// be hooked for interactive non-login shells; the build log says so.
var hookTemplate = template.Must(template.New("60-shell-hooks").Parse(`RUN <<'SANDCAST_EOF'
set -eu
install -d /etc/profile.d {{.RedirectHome}}
cat > {{.LoginHookPath}} <<'SANDCAST_HOOK'
{{.LoginHook}}
SANDCAST_HOOK
chmod 0644 {{.LoginHookPath}}
cat > {{.RedirectHome}}/.profile <<'SANDCAST_HOOK'
{{.RedirectProfile}}
SANDCAST_HOOK
chmod 0644 {{.RedirectHome}}/.profile
cat > /tmp/sandcast-bashrc-hook <<'SANDCAST_HOOK'
{{.BashrcHook}}
SANDCAST_HOOK
sysrc=
bash_bin=$(command -v bash 2>/dev/null || true)
if [ -n "$bash_bin" ]; then
  for f in{{range .SystemBashrcPaths}} {{.}}{{end}}; do
    if grep -qsF "$f" "$bash_bin"; then sysrc=$f; break; fi
  done
fi
if [ -n "$sysrc" ]; then
  install -d "$(dirname "$sysrc")"
  hook=/tmp/sandcast-bashrc-hook hook_begin='{{.HookBegin}}' hook_end='{{.HookEnd}}'
{{.HookInstall}}elif [ -n "$bash_bin" ]; then
  echo "sandcast: $bash_bin reads no system bashrc, so an interactive non-login bash that a runtime starts directly cannot be hooked" >&2
fi
rm -f /tmp/sandcast-bashrc-hook
SANDCAST_EOF
`))

// hookInstallScript prepends the hook block in the file $hook to the system
// bashrc $sysrc. A block of a previous sandcast build between $hook_begin
// and $hook_end (a base image that sandcast built with other targets, or a
// rebuild after an upgrade that changed the hook) is stripped first rather
// than kept, so the file always carries the block of the current plan once;
// the build log says when that happened. Prepending keeps the block before
// the distribution's early return for non-interactive shells.
const hookInstallScript = `  if grep -qsF "$hook_begin" "$sysrc"; then
    echo "sandcast: replacing the shell hook block of a previous sandcast build in $sysrc" >&2
    awk -v b="$hook_begin" -v e="$hook_end" '$0 == b { skip = 1 } !skip { print } $0 == e { skip = 0 }' "$sysrc" > "$sysrc.sandcast.rest"
  else
    cat "$sysrc" > "$sysrc.sandcast.rest" 2>/dev/null || :
  fi
  { cat "$hook"; cat "$sysrc.sandcast.rest"; } > "$sysrc.sandcast"
  rm -f "$sysrc.sandcast.rest"
  mv "$sysrc.sandcast" "$sysrc"
  chmod 0644 "$sysrc"
`

// hookTargets returns the commands the shell hooks replace an interactive
// bash with: the curated shell for a top-level shell, and for a bash the
// user starts inside a curated session, bash itself without home startup
// files (the launcher for the bash kind, a bash without any rc otherwise).
// For the zsh kind, NoSwitch keeps bash when the user set
// SANDCAST_NO_SHELL_SWITCH (spec 002 FR-008).
func hookTargets(p *plan.Plan) shell.HookTargets {
	switch plan.ShellKind(p) {
	case "zsh":
		zsh := shell.HookTarget{Program: shell.ZshProgram}
		return shell.HookTargets{Top: zsh, TopLogin: shell.HookTarget{Program: shell.ZshProgram, Args: "-l"}, Nested: shell.PlainBash, NoSwitch: shell.PlainBash}
	case "bash":
		launcher := shell.HookTarget{Program: plan.ShellLoginPath}
		return shell.HookTargets{Top: launcher, TopLogin: launcher, Nested: launcher}
	default:
		return shell.HookTargets{Top: shell.PlainBash, TopLogin: shell.PlainBash, Nested: shell.PlainBash}
	}
}

// hookExports are the variables the hooks export beyond the session
// environment script, which carries the relocation variables (they are in
// the plan's image env, where the relocation values win): SHELL for the zsh
// kind. OpenShell sets SHELL=/bin/bash for its sessions, and a program that
// starts $SHELL from the curated zsh (tmux, an editor's terminal) would get
// a login bash that the hooks turn into the nested bare bash. The curated
// zsh owns SHELL (see shell.ZshEnvExport).
func hookExports(p *plan.Plan) []shell.Export {
	if plan.ShellKind(p) == "zsh" {
		return []shell.Export{{Name: "SHELL", Value: shell.ZshProgram}}
	}
	return nil
}

// sessionEnvPath is the session environment script the launchers, the
// hooks and the global zshenv source, or "" when the plan bakes none.
func sessionEnvPath(p *plan.Plan) string {
	if NeedsSessionEnv(p) {
		return plan.SessionEnvPath
	}
	return ""
}

